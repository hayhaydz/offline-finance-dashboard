import crypto from "node:crypto";

/**
 * Envelope encryption core (openspec/changes/envelope-encryption-keyring).
 *
 * Per-user data is encrypted under a random 256-bit DataKey. Each credential
 * (password, WebAuthn PRF, recovery passphrase) wraps an INDEPENDENT copy of
 * that DataKey as a "slot" — LUKS keyslot / age recipient model:
 *
 *   slot = AES-256-GCM(credential_key, DataKey)
 *
 * Adding / rotating / revoking a credential only adds / rewrites / removes its
 * slot row. The DataKey itself never changes (except explicit full rotation)
 * and is never persisted in recoverable form.
 *
 * Every cryptographic operation lives in node:crypto / @node-rs/argon2 —
 * this module only orchestrates.
 */

export const SLOT_AAD_VERSION = "ofd-slot-v1";
export const DATA_KEY_BYTES = 32; // 256-bit
export const SLOT_IV_BYTES = 12; // GCM standard 96-bit IV

export type SlotKind =
	| "password"
	| "webauthn-prf"
	| "recovery-passphrase"
	| (string & {}); // future slot kinds (L3/L4 roadmap) — no keyring migration

/** Error thrown when slot unwrap fails (tamper, wrong key, wrong slot). */
export class EnvelopeError extends Error {
	constructor(
		readonly code:
			| "TAMPERED"
			| "WRONG_SLOT"
			| "BAD_FORMAT"
			| "UNSUPPORTED_VERSION",
		message: string,
	) {
		super(message);
		this.name = "EnvelopeError";
	}
}

/** AAD binds a wrapped slot to its identity — versioned for future agility. */
export interface SlotAAD {
	kind: SlotKind;
	userId: number;
	slotId: string;
}

function encodeSlotAAD(aad: SlotAAD): Buffer {
	return Buffer.from(
		`${SLOT_AAD_VERSION}|${aad.kind}|${aad.userId}|${aad.slotId}`,
		"utf8",
	);
}

/** CSPRNG 256-bit DataKey. Exists raw only in process memory. */
export function generateDataKey(): Buffer {
	return crypto.randomBytes(DATA_KEY_BYTES);
}

/**
 * Random slot identifier (128-bit hex). Generated by the caller BEFORE
 * wrapping so the AAD and the stored row reference the same id.
 */
export function generateSlotId(): string {
	return crypto.randomBytes(16).toString("hex");
}

export interface WrappedSlot {
	/** Hex-encoded ciphertext + GCM tag. */
	wrappedKey: string;
	/** Hex-encoded 12-byte IV. */
	iv: string;
}

/** Wrap a DataKey copy under a credential-derived key. */
export function wrapSlot(
	dataKey: Uint8Array,
	slotKey: Uint8Array,
	aad: SlotAAD,
): WrappedSlot {
	if (slotKey.length !== 32) {
		throw new EnvelopeError("BAD_FORMAT", "Slot key must be 256-bit");
	}
	const iv = crypto.randomBytes(SLOT_IV_BYTES);
	const cipher = crypto.createCipheriv("aes-256-gcm", slotKey, iv);
	cipher.setAAD(encodeSlotAAD(aad));
	const ciphertext = Buffer.concat([cipher.update(dataKey), cipher.final()]);
	const tag = cipher.getAuthTag();
	return {
		wrappedKey: Buffer.concat([ciphertext, tag]).toString("hex"),
		iv: iv.toString("hex"),
	};
}

/**
 * Unwrap a DataKey copy. Throws EnvelopeError on any tampering, wrong
 * credential key, or AAD mismatch (slot moved between users/kinds/slots).
 */
export function unwrapSlot(
	wrappedSlot: WrappedSlot,
	slotKey: Uint8Array,
	aad: SlotAAD,
): Buffer {
	if (slotKey.length !== 32) {
		throw new EnvelopeError("BAD_FORMAT", "Slot key must be 256-bit");
	}

	let raw: Buffer;
	try {
		raw = Buffer.from(wrappedSlot.wrappedKey, "hex");
	} catch {
		throw new EnvelopeError("BAD_FORMAT", "Wrapped slot is not valid hex");
	}
	const iv = Buffer.from(wrappedSlot.iv, "hex");
	if (raw.length <= 16 || iv.length !== SLOT_IV_BYTES) {
		throw new EnvelopeError("BAD_FORMAT", "Wrapped slot has invalid shape");
	}

	const ciphertext = raw.subarray(0, raw.length - 16);
	const tag = raw.subarray(raw.length - 16);

	const decipher = crypto.createDecipheriv("aes-256-gcm", slotKey, iv);
	decipher.setAAD(encodeSlotAAD(aad));
	decipher.setAuthTag(tag);
	try {
		return Buffer.concat([decipher.update(ciphertext), decipher.final()]);
	} catch {
		// GCM failure covers: tampered bytes, wrong key, and AAD mismatch
		// (wrong user / slot / kind) uniformly — callers never learn which.
		throw new EnvelopeError(
			"TAMPERED",
			"Slot unwrap failed: tampered, wrong credential, or wrong slot",
		);
	}
}

/**
 * Best-effort key zeroization. V8 copies buffers unpredictably, so this is
 * damage reduction (documented hot-tier ceiling), not a guarantee.
 */
export function zeroize(
	...buffers: Array<Uint8Array | null | undefined>
): void {
	for (const buf of buffers) {
		if (buf && buf.length > 0) {
			try {
				buf.fill(0);
			} catch {
				// Read-only or detached views — nothing more we can do.
			}
		}
	}
}
